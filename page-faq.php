    document.body.style.overflow = 'hidden';
  }

  function closeVersePopup(){
    if (!vpOverlay) return;
    vpOverlay.classList.remove('open');
    vpOverlay.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
  }

  document.addEventListener('click', function(e){
    var t = e.target.closest ? e.target.closest('.vref, .vref-cite') : null;
    if (t) {
      e.preventDefault();
      e.stopPropagation();
      var v = t.getAttribute('data-v');
      if (v) openVersePopup(v);
      return;
    }
    if (vpClose && e.target === vpClose) { closeVersePopup(); return; }
    if (vpOverlay && e.target === vpOverlay) { closeVersePopup(); return; }
  });

  document.addEventListener('keydown', function(e){
    if (e.key === 'Escape' && vpOverlay && vpOverlay.classList.contains('open')) closeVersePopup();
  });
})();
