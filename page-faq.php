      if (open) {
        item.classList.remove('open');
        btn.setAttribute('aria-expanded', 'false');
        panel.style.maxHeight = '0px';
      } else {
        item.classList.add('open');
        btn.setAttribute('aria-expanded', 'true');
        panel.style.maxHeight = panel.scrollHeight + 'px';
      }
    });
  });
  window.addEventListener('resize', function(){
    document.querySelectorAll('.faq-item.open .faq-a').forEach(function(p){
      p.style.maxHeight = p.scrollHeight + 'px';
    });
  });

  var search = document.getElementById('faqSearch');
  var empty = document.getElementById('faqEmpty');
  var cats = document.querySelectorAll('.faq-cat');
  if (search) {
    search.addEventListener('input', function(){
      var q = search.value.trim().toLowerCase();
      var anyVisible = false;
      cats.forEach(function(cat){
        var catHasMatch = false;
        cat.querySelectorAll('.faq-item').forEach(function(item){
          var text = item.textContent.toLowerCase();
          var match = !q || text.indexOf(q) !== -1;
          item.style.display = match ? '' : 'none';
          if (match) catHasMatch = true;
        });
        cat.style.display = catHasMatch ? '' : 'none';
        if (catHasMatch) anyVisible = true;
      });
      empty.style.display = anyVisible ? 'none' : 'block';
    });
  }

  var vpOverlay = document.getElementById('versePopupOverlay');
  var vpBody = document.getElementById('versePopupBody');
  var vpClose = document.getElementById('versePopupClose');

  function escapeHtml(s){
    return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
  }

  function openVersePopup(refs){
    if (!vpOverlay || !vpBody) return;
    var list = refs.split(',');
    var html = '';
    list.forEach(function(ref){
      ref = ref.trim();
      var v = GA_VERSES[ref];
      if (!v) return;
      html += '<div class="vp-block">'
        + '<span class="vp-chip">' + escapeHtml(ref) + '</span>'
        + '<div class="vp-ar">' + v.ar + '</div>'
        + '<p class="vp-en">' + (v.ta ? v.ta : '<em>தமிழ் மொழிபெயர்ப்பு விரைவில் கிடைக்கும், இன்ஷா அல்லாஹ்.</em>') + '</p>'
