<p>இது பல பில்லியன் ஆண்டுகளுக்கு முன்பு தொடங்கியது: மேலான சமூகத்தில் ஒரு கலகம் ஏற்பட்டது (<a href="#" class="vref" data-v="38:69">38:69</a>). உயர் பதவியிலிருந்த படைப்புகளில் ஒன்றான சாத்தான், கடவுள் தனக்கு அளித்த ஆற்றல்கள் தன்னைக் கடவுளுடன் சேர்ந்து இன்னொரு கடவுளாக ஆகத் தகுதியுடையவனாக்குகின்றன என்று ஆணவத்துடன் எண்ணினான். இவ்வாறு அவன் கடவுளின் ஏகோபித்த அதிகாரத்திற்குச் சவால் விடுத்தான். சாத்தானின் இந்த எண்ணம் இறைநிந்தனை மட்டுமல்ல, தவறானதும் கூட — கடவுளாக இருப்பதற்கான தகுதியும் ஆற்றலும் கடவுளுக்கு மட்டுமே உண்டு, வேறு யாருக்கும் இல்லை. சாத்தானின் இந்த இறைநிந்தனையின் விளைவாக மேலான சமூகத்தில் பிளவு ஏற்பட்டு, கடவுளின் ராஜ்ஜியத்தின் அனைவரும் நான்கு வகைகளாகப் பிரிக்கப்பட்டனர்:</p>
<p><strong>வானவர்கள்:</strong> கடவுளின் ஏகோபித்த அதிகாரத்தை நிலைநாட்டிய படைப்புகள்.</p>
<p><strong>விலங்குகள்:</strong> கிளர்ச்சி செய்தவர்கள் (விலங்குகள், மரங்கள், நட்சத்திரங்கள் முதலியன); மனந்திரும்பி அவரது ராஜ்ஜியத்தில் மீண்டும் சேரும் கடவுளின் வாய்ப்பைப் பயன்படுத்திக் கொண்டவர்கள்.</p>
<p><strong>ஜின்கள்:</strong> சாத்தான் “கடவுளாக” இருக்கத் தகுதியுடையவன் என்று அவனுடன் உடன்பட்ட படைப்புகள்.</p>
<p><strong>மனிதர்கள்:</strong> முடிவெடுக்காமல் இருந்த படைப்புகள்; கடவுளின் ஏகோபித்த அதிகாரத்தின் பக்கம் உறுதியாக நிற்கத் தவறியவர்கள்.</p>
<p><strong>மிக்க கருணையாளன்</strong></p>
<p>கடவுளின் ஏகோபித்த அதிகாரத்தை ஆதரிக்காத படைப்புகளை அவர் வெளியேற்றுவார் என்று வானவர்கள் எதிர்பார்த்தனர் (<a href="#" class="vref" data-v="2:30">2:30</a>). ஆனால் கடவுள் மிக்க கருணையாளன்; நமது தவற்றைக் கண்டித்து விலகுவதற்கு நமக்கு ஒரு வாய்ப்பை வழங்க அவர் தீர்மானித்தார்; வானவர்கள் அறியாததை அவர் அறிவார் என்றும் அவர்களுக்குத் தெரிவித்தார் (<a href="#" class="vref" data-v="2:30">2:30</a>). சில படைப்புகள் மீட்சிக்கான வாய்ப்புக்குத் தகுதியானவை என்பதைக் கடவுள் அறிந்திருந்தார்.</p>
<p>ஒருவர் விமானம் ஓட்டத் தன்னால் முடியும் என்று கூறினால், அவரது கூற்றைச் சோதிக்க சிறந்த வழி, அவரிடம் ஒரு விமானத்தைக் கொடுத்து ஓட்டச் சொல்வதே. சாத்தானின் வாதத்திற்குப் பதிலாகக் கடவுள் செய்யத் தீர்மானித்தது இதுவே. கடவுள் ஏழு பெரும் பிரபஞ்சங்களைப் படைத்து, “பூமி” என்னும் சிறு துகளின் மீது சாத்தானை ஒரு தெய்வமாக நியமிக்கப்போவதாக வானவர்களுக்குத் தெரிவித்தார் (<a href="#" class="vref" data-v="2:30">2:30</a>). சாத்தானை ஒரு தற்காலிக “தெய்வமாக” நியமித்தது தொடர்பான குர்ஆனின் விவரங்கள் (<a href="#" class="vref" data-v="36:60">36:60</a>) முந்தைய வேதத்தை உறுதிப்படுத்துகின்றன.</p>
<p>கடவுளின் திட்டம், மரணத்தைப் படைத்து (<a href="#" class="vref" data-v="67:1">67:1</a>, <a href="#" class="vref" data-v="67:2">67:2</a>), பின்னர் மனிதர்களையும் ஜின்களையும் இவ்வுலகிற்குக் கொண்டுவருவதாக இருந்தது. இதனால் அவர்கள் எந்தச் சார்பும் இல்லாமல் புதிதாகத் தொடங்கி, கடவுளின் ஏகோபித்த அதிகாரத்தையோ சாத்தானின் இணைவைப்புக் கொள்கையையோ நிலைநாட்டுவதற்கான முழு சுதந்திரத்தைப் பெறுகிறார்கள். இந்த முக்கிய முடிவை எடுப்பதற்காக ஒவ்வொரு மனிதனும் கடவுளின் ஏகோபித்த அதிகாரத்தை வலியுறுத்தும் ஒரு செய்தியையும், சாத்தான் தனது இணைவைப்புக் கொள்கைகளைத் தள்ளும் ஒரு செய்தியையும் பெறுகிறான்.</p>
<p>நமக்கு ஒரு தொடக்க உதவியாக, மிக்க கருணையாளன் நம்மை இவ்வுலகிற்கு அனுப்புவதற்கு முன் அனைத்து மனிதர்களையும் தன் முன் ஒன்று திரட்டினான்; அவனே நமது இரட்சகனும் எஜமானனும் என்று நாம் சாட்சி கூறினோம் (<a href="#" class="vref" data-v="7:172">7:172</a>). ஆகவே, கடவுளின் ஏகோபித்த அதிகாரத்தை நிலைநாட்டுவது ஒவ்வொரு மனிதனின் இயல்பிலும் இணைந்த இயற்கையான உள்ளுணர்வாகும்.</p>
<p>கிளர்ச்சியாளர்களை மரணமடையச் செய்த பின், மனிதர்கள் மற்றும் ஜின்களின் ஆத்மாக்கள் ஒரு சிறப்புக் களஞ்சியத்தில் வைக்கப்பட்டன. பின்னர் சோதனைக் காலத்தில் ஜின்களுக்கும் மனிதர்களுக்கும் ஆத்மாக்களைக் குடியமர்த்த ஏற்ற உடல்களைக் கடவுள் படைத்தார். முதல் ஜின் உடல் நெருப்பிலிருந்து படைக்கப்பட்டது; சாத்தான் அந்த உடலுக்கு நியமிக்கப்பட்டான் (<a href="#" class="vref" data-v="15:27">15:27</a>). முதல் மனித உடல் பூமியின் பொருளான களிமண்ணிலிருந்து படைக்கப்பட்டது (<a href="#" class="vref" data-v="15:26">15:26</a>); கடவுள் முதல் மனித ஆத்மாவை அந்த உடலுக்கு நியமித்தார். பூமியில் வானவர்கள் மனிதர்களுக்குப் பணிவிடை செய்ய வேண்டும் — அவர்களைக் காக்க, அவர்களுக்காகக் காற்றையும் மழையையும் செலுத்த, வாழ்வாதாரங்களைப் பகிர்ந்தளிக்க — என்பது தெய்வீகத் திட்டம். இதையே குர்ஆன் உருவகமாக, வானவர்கள் ஆதமின் முன் சிரம் பணிந்து விழுந்ததாகக் குறிப்பிடுகிறது. மனித இனத்திற்குப் பணிவிடை செய்யும் எதிலும் சாத்தான் நிச்சயமாக ஈடுபட மறுத்தான் (<a href="#" class="vref" data-v="2:34">2:34</a>, <a href="#" class="vref" data-v="7:11">7:11</a>, <a href="#" class="vref" data-v="17:61">17:61</a>, <a href="#" class="vref" data-v="18:50">18:50</a>, <a href="#" class="vref" data-v="20:116">20:116</a>).</p>
<p>“லூசிபரே, நீ உன் இதயத்தில் சொன்னாய்: ‘நான் வானங்களுக்கு மேல் ஏறுவேன்; கடவுளின் நட்சத்திரங்களுக்கு மேல் என் சிம்மாசனத்தை அமைப்பேன்; வடக்கின் ஒதுக்கிடங்களில் உள்ள சபையின் மலையில் அமர்வேன்; மேகங்களின் உச்சிகளுக்கு மேல் ஏறுவேன்; நான் உன்னதமானவரைப் போல் இருப்பேன்!’” — ஏசாயா 14:13–15</p>
<p>“பிசாசு இயேசுவை மிக உயர்ந்த ஒரு மலைக்குக் கொண்டுபோய், உலகின் எல்லா இராச்சியங்களையும் அவற்றின் மகிமையோடு காட்டி, ‘நீர் என் முன் விழுந்து வணங்கினால், இவை அனைத்தையும் உமக்குத் தருவேன்’ என்றான். அதற்கு இயேசு அவனிடம், ‘சாத்தானே, அப்பால் போ! “உன் கடவுளாகிய ஆண்டவரை வணங்கு; அவர் ஒருவரையே தொழுது கொள்” என்று வேதத்தில் எழுதப்பட்டிருக்கிறது’ என்றார்.” — மத்தேயு 4:8–10 & லூக்கா 4:5–8</p>
<p>ஆதமின் உடல் பூமியில் இருந்தபோது, உண்மையான மனிதரான ஆத்மா வெளிப்புற பிரபஞ்சத்திலுள்ள சொர்க்கத்தில் அனுமதிக்கப்பட்டது. கடவுள் ஆதமுக்குச் சில கட்டளைகளை வழங்கினார்; அவையே தடுக்கப்பட்ட மரத்தால் குறிக்கப்படுகின்றன. ஆதமுக்கு சாத்தானின் செய்தியைக் கொண்டுசேர்க்க சாத்தான் அவரது துணையாக நியமிக்கப்பட்டான். மற்றதெல்லாம் வரலாறு.</p>
<p>ஒரு மனிதக் குழந்தை பிறக்கும் ஒவ்வொரு முறையும், ஆத்மாக்களின் களஞ்சியத்திலிருந்து ஒரு மனித ஆத்மா அந்தப் புதிய குழந்தைக்கு நியமிக்கப்படுகிறது. கடவுள் தனது அறிவுக்கு ஏற்ப ஆத்மாக்களை நியமிக்கிறார் (<a href="#" class="vref" data-v="28:68">28:68</a>). ஒவ்வோர் ஆத்மாவும் ஒரு குறிப்பிட்ட உடலுக்கும் குறிப்பிட்ட சூழ்நிலைகளுக்கும் தகுதியானது. எந்த ஆத்மாக்கள் நல்லவை, எவை தீயவை என்பதை கடவுள் மட்டுமே அறிவார். நமது குழந்தைகள் கடவுளின் திட்டத்தின்படி நமது இல்லங்களுக்கு நியமிக்கப்படுகிறார்கள்.</p>
<p>சாத்தானின் கண்ணோட்டத்தைப் பிரதிநிதித்துவப்படுத்த, ஒரு தனிப்பட்ட ஜின் ஆத்மாவும் அந்தப் புதிய மனிதருக்கு நியமிக்கப்படுகிறது. எந்த ஜின்னின் உடலும் பெற்றோர் ஜின்களிலிருந்து உருவாகும்போது, ஜின் ஆத்மா ஒரு சுயாதீனமான தனிநபருடையது. ஜின்கள் சாத்தானின் வழித்தோன்றல்கள் (<a href="#" class="vref" data-v="7:27">7:27</a>, <a href="#" class="vref" data-v="18:50">18:50</a>). நியமிக்கப்பட்ட ஜின் பிறப்பிலிருந்து மரணம் வரை அந்த மனிதருடன் இருந்து, தீர்ப்பு நாளில் முக்கிய சாட்சியாகச் செயல்படுகிறது (<a href="#" class="vref" data-v="50:23">50:23</a>). மனித ஆத்மாவுக்கும் ஜின் ஆத்மாவுக்கும் இடையே, இருவரும் ஒரே கருத்தை ஏற்கும் வரை நமது தலைகளுக்குள் தொடர்ச்சியான விவாதம் நடைபெறுகிறது.</p>
<p><strong>அசல் பாவம்</strong></p>
<p>பொதுவான நம்பிக்கைக்கு மாறாக, “அசல் பாவம்” என்பது தடுக்கப்பட்ட மரத்திலிருந்து ஆதம் உண்டபோது கடவுளின் சட்டத்தை மீறியது அல்ல. பெரும் பூசலின் போது கடவுளின் ஏகோபித்த அதிகாரத்தை நிலைநாட்டத் தவறியதே அசல் பாவம். மனிதன் தன் ஜின் துணையை அந்த அசல் பாவத்தைக் கண்டித்து, கடவுளின் ஏகோபித்த அதிகாரத்தை நிலைநாட்டும்படி இணங்க வைத்தால், தீர்ப்பு நாளில் இரு படைப்புகளும் கடவுளின் நித்திய ராஜ்ஜியத்திற்கு மீட்கப்படுகின்றன. ஆனால் ஜின் துணை, மனிதனை சாத்தானின் உருவ வழிபாட்டுக் கருத்துகளை ஆதரிக்கும்படி இணங்க வைத்தால், இரு படைப்புகளும் கடவுளின் ராஜ்ஜியத்திலிருந்து என்றென்றும் வெளியேற்றப்படுகின்றன.</p>
<p>தன் கருத்தை முன்னெடுக்க, முஹம்மத், ஜீஸஸ், மேரி, புனிதர்கள் போன்ற ஆற்றலற்ற படைப்புகளை வழிபடுவதை சாத்தானும் அவனது பிரதிநிதிகளும் ஆதரிக்கிறார்கள். நமது இணைவைப்புப் போக்குகளால்தான் நாம் இங்கு இருக்கிறோம் என்பதால், நம்மில் பெரும்பாலோர் சாத்தானுக்கு எளிதில் இரையாகிவிடுகிறோம்.</p>
